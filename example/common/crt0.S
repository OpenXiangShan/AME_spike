    /* Shared startup entry for the standalone AME examples. */
    .section .text.init
    .globl _start
    .type _start, @function
_start:
    .option push
    .option norelax
    la gp, __global_pointer$
    .option pop
    la sp, __stack_top

    /* C code and Ztt tests use scalar FP, vector, and AME architectural state. */
    li t0, (1 << 13) | (1 << 9) | (1 << 25)
    csrs mstatus, t0

    la t0, __bss_start
    la t1, __bss_end
1:
    bgeu t0, t1, 2f
    sd zero, 0(t0)
    addi t0, t0, 8
    j 1b
2:
    call ztt_baremetal_start
3:
    wfi
    j 3b
    .size _start, . - _start
